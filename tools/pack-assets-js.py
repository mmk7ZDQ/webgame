#!/usr/bin/env python3
"""
把一张地图及其引用的资源打包成 JS 对象，供 Web 端的 AssetManager 读取。

为什么需要：RW 引擎的地图加载是同步的（AssetManager.open 返回 InputStream），
而浏览器里没有同步文件系统。把用到的文件预先 base64 打包成 window.__RW_ASSETS，
AssetManager.open 就能从里面拿到真数据 —— 引擎才真的能加载出一张地图。

用法：pack-assets-js.py <assets目录> <tmx相对路径> <输出.js>
"""
import base64
import json
import os
import re
import sys
import xml.etree.ElementTree as ET


def resolve(assets, base_dir, src):
    """RW 的 TMX/TSX 里 source 优先相对 assets/tilesets/，找不到再相对当前文件目录"""
    for cand in (os.path.join('tilesets', src), os.path.join(base_dir, src)):
        p = os.path.normpath(cand).replace('\\', '/')
        if os.path.isfile(os.path.join(assets, p)):
            return p
    return os.path.normpath(os.path.join(base_dir, src)).replace('\\', '/')


def collect(assets, tmx_rel):
    """从 TMX 出发，递归收集所有引用到的文件"""
    seen = {}
    stack = [tmx_rel]
    while stack:
        rel = stack.pop()
        rel = rel.replace('\\', '/')
        if rel in seen:
            continue
        full = os.path.join(assets, rel)
        if not os.path.isfile(full):
            print(f'  ! 缺失 {rel}')
            continue
        seen[rel] = full
        if not (rel.endswith('.tmx') or rel.endswith('.tsx')):
            continue
        try:
            root = ET.parse(full).getroot()
        except ET.ParseError:
            continue
        base = os.path.dirname(rel)
        # tileset source 指向外部 .tsx
        for ts in root.iter('tileset'):
            src = ts.get('source')
            if src:
                stack.append(resolve(assets, base, src))
        # image source 指向 png
        for im in root.iter('image'):
            src = im.get('source')
            if src:
                stack.append(resolve(assets, base, src))
    return seen


def main():
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(2)
    assets, tmx_rel, out_js = sys.argv[1], sys.argv[2], sys.argv[3]
    files = collect(assets, tmx_rel)
    print(f'收集 {len(files)} 个文件')

    bundle = {}
    total = 0
    for rel, full in sorted(files.items()):
        with open(full, 'rb') as f:
            data = f.read()
        bundle[rel] = base64.b64encode(data).decode('ascii')
        total += len(data)

    with open(out_js, 'w') as f:
        f.write('// AUTO-GENERATED by tools/pack-assets-js.py — 不要手工编辑\n')
        f.write('// 源：%s\n' % tmx_rel)
        f.write('window.__RW_ASSETS = {\n')
        for k, v in bundle.items():
            f.write('  %s: "%s",\n' % (json.dumps(k), v))
        f.write('};\n')
    print(f'✓ {out_js}  {len(bundle)} 个文件 / {total/1024:.0f} KB 原始')


if __name__ == '__main__':
    main()
